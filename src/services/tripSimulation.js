// ============================================================
//  حالة محاكاة القيادة — مشتركة بين المحاكي ونبضة الموقع
//
//  المحاكاة تدفع نقاطها إلى الخادم كنبضات حقيقية، و`SessionContext` يدفع
//  قراءات GPS الجهاز في الوقت نفسه كل ثانية أثناء الرحلة. الاثنان يكتبان
//  `providerLocation` على الطلب نفسه، فيرى العميل السيارة تقفز بين الطريق
//  وموقع الجهاز الحقيقي — لا تعطّل ظاهر، فقط تتبّع يبدو مكسوراً.
//
//  علَمٌ في وحدة مستقلّة لا حالة React: القارئ هو ردّ نداء `watchPosition`
//  المُنشأ مرّة واحدة عند بدء المراقبة، فقراءة أي حالة من داخله تتجمّد على
//  قيمتها الأولى. والوحدة تُقرأ لحظة كل نبضة فتعكس الواقع دائماً.
//
//  الأولوية للمحاكاة لا للجهاز: هي التي طُلبت صراحةً، والجهاز واقف أصلاً حين
//  تعمل — فكتم الأصدق نظرياً هنا هو الأصحّ عملياً.
// ============================================================

let active = false;

/** هل تقود المحاكاة الآن؟ يُقرأ لحظة كل نبضة موقع */
export const isSimulatingTrip = () => active;

/** يُستدعى من `useTripSimulation` عند البدء والإيقاف حصراً */
export const setSimulatingTrip = (value) => {
  active = !!value;
};
