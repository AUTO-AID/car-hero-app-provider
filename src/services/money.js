//  كانت الشاشات تكتب «د.أ» بينما تطبيق العميل كلّه بالليرة السورية
//  (`walletApi.CURRENCY`)، أي أن الفنّي والعميل يريان **عملتين مختلفتين
//  للمبلغ نفسه**. العقد هنا منسوخ عن عقد تطبيق العميل حرفياً كي تبقى العملة
//  قراراً واحداً في التطبيقين، ويكفي تغييرها هنا وهناك عند حسمها مع الخادم.
