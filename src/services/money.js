export const CURRENCY = "ل.س";

export const formatMoney = (value) => `${Number(value || 0).toLocaleString("ar-EG")} ${CURRENCY}`;

// الأرقام العربية للعدّادات والتواريخ — تطبيق العميل يعرض كل أرقامه بها،
// وخلط الأرقام اللاتينية بالعربية في شاشة واحدة يبدو سهواً لا اختياراً.
export const formatNumber = (value) => Number(value || 0).toLocaleString("ar-EG");
