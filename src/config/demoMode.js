/** المفتاح الرئيس — أطفئه بعد العرض فيعود كل شيء إلى سلوكه الأصلي */
export const DEMO_MODE = true;

/**
 * تبدأ محاكاة القيادة تلقائياً عند دخول شاشة «في الطريق»، ويختفي زرّها.
 *
 * الزرّ نفسه (`__DEV__` فقط) يظهر في التسجيل ويُقرأ كأداة تطوير مكشوفة في
 * فيديو مناقشة — والضغط عليه أمام اللجنة يفسد المشهد. التشغيل التلقائي يقع
 * في اللحظة الصحيحة تماماً: حين يعلن الفنّي أنه انطلق.
 */
export const DEMO_AUTO_DRIVE = true;

/**
 * سرعة السيارة في المحاكاة (كم/س).
 *
 * كانت ٣٥ (بعد أن كانت ١٠٨) — ولا تزال سريعة جداً لعين تراقب الخريطة عن
 * قرب: تقطع بضع مئات الأمتار خلال ثوانٍ معدودة. نصف القيمة (~١٧٫٥) يمنحها
 * وقتاً كافياً لملاحظة الحركة والاتجاه دون أن تبدو السيارة طائرة.
 */
export const DEMO_DRIVE_SPEED_KMH = 35 / 2;

/** هل تعمل تسهيلات العرض الآن؟ محروسة بوضع التطوير أيضاً */
export const demoDriveEnabled = () => __DEV__ && DEMO_MODE && DEMO_AUTO_DRIVE;
